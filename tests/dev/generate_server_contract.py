#!/usr/bin/env python3
"""Generate tests/helpers/serverContract.bs from a silo-server checkout.

The harness specs check hand-built playback bodies against the v2 OpenAPI
request schemas and build them from the server's own fixtures. This script
copies both into BrighterScript so the headless test package needs no file I/O.
Run it with the standard library only, from the repository root:

    python3 -I tests/dev/generate_server_contract.py /path/to/silo-server [ref]
    npm run format

`ref` defaults to origin/main; files are read with `git show`, so the checkout
is never modified. Commit the regenerated file together with the server commit
it names.
"""

import json
import subprocess
import sys

ROOT_SCHEMAS = ["PlaybackStartBody", "PlaybackReplanBody", "PlaybackProgressBody", "PlaybackStopBody"]
FIXTURES = [
    "get_system_info_ok",
    "list_profiles_ok",
    "get_watch_state_ok",
    "playback_capability_available",
    "playback_start_opaque_ids",
]
CONSTRAINTS = ["enum", "minimum", "maximum", "minLength", "maxLength", "maxItems"]
OUTPUT = "tests/helpers/serverContract.bs"


def git_show(checkout, ref, path):
    return subprocess.run(
        ["git", "-C", checkout, "show", f"{ref}:{path}"], check=True, capture_output=True, text=True
    ).stdout


def literal(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return json.dumps(value)
    if isinstance(value, str):
        return '"' + value.replace('"', '""') + '"'
    if isinstance(value, list):
        return "[" + ", ".join(literal(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{literal(key)}: {literal(item)}" for key, item in value.items()) + " }"
    raise TypeError(type(value))


def property_shape(schema, refs):
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        refs.append(name)
        return {"type": "ref", "ref": name}
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next(item for item in kind if item != "null")
    if kind == "array":
        shape = {"type": "array", "items": property_shape(schema.get("items", {}), refs)}
    elif kind == "object" and isinstance(schema.get("additionalProperties"), dict):
        shape = {"type": "map", "values": property_shape(schema["additionalProperties"], refs)}
    else:
        shape = {"type": kind or "any"}
    for key in CONSTRAINTS:
        if key in schema:
            shape[key] = schema[key]
    return shape


def collect(schemas):
    shapes = {}
    queue = list(ROOT_SCHEMAS)
    while queue:
        name = queue.pop(0)
        if name in shapes:
            continue
        schema = schemas[name]
        refs = []
        properties = {key: property_shape(value, refs) for key, value in schema.get("properties", {}).items()}
        shapes[name] = {"required": schema.get("required", []), "properties": properties}
        queue.extend(refs)
    return shapes


def chunks(text, size=88):
    pieces = []
    while text:
        piece = text[:size]
        # Never split a doubled quote across two literals.
        while piece.endswith('"') and len(piece) < len(text) and text[len(piece)] == '"':
            piece = text[: len(piece) + 1]
        pieces.append(piece)
        text = text[len(piece):]
    return pieces


def aa_block(entries, indent):
    pad = " " * indent
    lines = []
    for index, (key, value) in enumerate(entries):
        comma = "," if index < len(entries) - 1 else ""
        lines.append(f"{pad}{key}: {value}{comma}")
    return lines


def render(checkout, ref):
    commit = subprocess.run(
        ["git", "-C", checkout, "rev-parse", ref], check=True, capture_output=True, text=True
    ).stdout.strip()
    openapi = json.loads(git_show(checkout, ref, "contracts/api/v2/openapi.json"))
    shapes = collect(openapi["components"]["schemas"])

    out = [
        "' Generated by tests/dev/generate_server_contract.py; do not edit by hand.",
        f"' Source: silo-server {commit}",
        "' (contracts/api/v2/openapi.json request schemas and contracts/api/v2/fixtures/).",
        "' silo-server is AGPL-3.0-or-later, the same licence as this repository.",
        "namespace tests.contract",
        "",
        "    ' Request schemas: required members and each property's type and bounds.",
        "    function shapes() as Object",
        "        return {",
    ]
    shape_entries = []
    for name, shape in shapes.items():
        props = ["{"] + aa_block([(key, literal(value)) for key, value in shape["properties"].items()], 20) + ["                }"]
        body = [
            "{",
            f"                required: {literal(shape['required'])},",
            "                properties: " + props[0],
            *props[1:],
            "            }",
        ]
        shape_entries.append((name, body))
    for index, (name, body) in enumerate(shape_entries):
        body = list(body)
        if index < len(shape_entries) - 1:
            body[-1] += ","
        out.append(f"            {name}: " + body[0])
        out.extend(body[1:])
    out += ["        }", "    end function", ""]

    out += [
        "    ' Server fixtures, parsed on demand.",
        "    function fixture(name as String) as Object",
        "        texts = {",
    ]
    fixture_entries = []
    for name in FIXTURES:
        text = json.dumps(json.loads(git_show(checkout, ref, f"contracts/api/v2/fixtures/{name}.json")), separators=(",", ":"))
        pieces = [literal(piece) for piece in chunks(text)]
        fixture_entries.append((name, pieces))
    for index, (name, pieces) in enumerate(fixture_entries):
        out.append(f"            {name}: [")
        out.extend(f"                {piece}" for piece in pieces)
        out.append("            ]" + ("," if index < len(fixture_entries) - 1 else ""))
    out += [
        "        }",
        '        return ParseJson(texts[name].Join(""))',
        "    end function",
        "",
        "end namespace",
        "",
    ]
    return "\n".join(out)


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    ref = sys.argv[2] if len(sys.argv) == 3 else "origin/main"
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write(render(sys.argv[1], ref))


if __name__ == "__main__":
    main()
